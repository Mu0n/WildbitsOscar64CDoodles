//Left 0xD600 (1,2,3), Right D610 (1,2,3), Noise (D600), unused
uint16_t psgAddr[8] = {0xD600, 0xD600, 0xD600, 0xD610, 0xD610, 0xD610, 0xD600, 0x0000};
void shutPSG()
{
	uint8_t i;
	for(i=1;i<=7;i+=2)
	{
		POKE(PSG_LEFT,  0x9F | (i<<4));
		POKE(PSG_RIGHT, 0x9F | (i<<4));
	}
}

uint8_t chanToBytes[8] = {0x00, 0x20, 0x40, 0x00, 0x20, 0x40, 0x70, 0x00};
//chan is either 0x00 (chan1), 0x20 (chan2), 0x40 (chan3) or 0x70 (noise)
//addr is from psgAddr[i] where i = 0 to 6 (7 unused)
//lobyte is from psgLow[]
//hibyte is from psgHigh[]
//velo is from 0x0 to 0xF
void psgNoteOn(uint8_t chan, uint16_t addr, uint8_t loByte, uint8_t hiByte, uint8_t velo)
{
	if(addr == 0x0000) return;
	POKE(addr,0x90 | chan | velo); // the formula controls the nybble for tone 0 attenuation. ie a 0xFF here = silence, while 0x00 is max volume. the higher the midi in velocity, the lower this number becomes
	POKE(addr,loByte | chan); 
	POKE(addr,hiByte); //noise channel only has lobyte, so give it 0x00 when noise is wanted
}

void psgLegato(uint8_t chan, uint16_t addr, uint8_t loByte, uint8_t hiByte, uint8_t velo)
{
	if(addr == 0x0000) return;
	POKE(addr,0x90 | chan | velo); // the formula controls the nybble for tone 0 attenuation. ie a 0xFF here = silence, while 0x00 is max volume. the higher the midi in velocity, the lower this number becomes
	POKE(addr,loByte | chan); 
	POKE(addr,hiByte); //noise channel only has lobyte, so give it 0x00 when noise is wanted
}

void psgNoteOff(uint8_t chan,uint16_t addr)
{
	if(addr == 0x0000) return;
	POKE(addr,0x9F | chan); //chan is either 0x00 (chan1), 0x20 (chan2), 0x40 (chan3) or 0x70 (noise)
}

void setMonoPSG()
{
	uint8_t sys1;
	
	sys1=PEEK(PSG_SYS1);
	sys1 = sys1 & 0b11111011;
	POKE(PSG_SYS1,sys1);
}
void setStereoPSG() //most often used
{
	uint8_t sys1;
	
	sys1=PEEK(PSG_SYS1);
	sys1 = sys1 & 0b11111111;
	POKE(PSG_SYS1,sys1);
}

